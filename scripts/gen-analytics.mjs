// Generate the analytics event constants for the iOS and Android apps.
//
// design/analytics.json is the single source of truth for the event
// vocabulary. This exists for the same reason gen-design-tokens.mjs does: two
// apps that log "round_end" and "roundEnd" produce two datasets that look like
// one, and nobody notices until a quarter of the data has to be thrown away.
// Neither app is allowed to spell an event name itself.
//
// Emits:
//   build/analytics/AnalyticsEvents.swift  (enum Event, enum Param)
//   build/analytics/AnalyticsEvents.kt     (package com.mercato.analytics)
//
// Output is generated and gitignored, the same convention the tokens, the
// strings, the sounds and the UniFFI bindings follow.
//
// Run: node scripts/gen-analytics.mjs
import fs from "fs";
import path from "path";

const ROOT = new URL("..", import.meta.url).pathname;
const SRC = path.join(ROOT, "design/analytics.json");
const OUT = path.join(ROOT, "build/analytics");

const die = (msg) => {
  console.error(`error: ${msg}`);
  process.exit(1);
};

let spec;
try {
  spec = JSON.parse(fs.readFileSync(SRC, "utf8"));
} catch (e) {
  die(`cannot read ${SRC}: ${e.message}`);
}

const events = spec.events || {};
if (!Object.keys(events).length) die("no events declared");

// Google's own limits, checked here rather than discovered in the console six
// weeks later when an event had silently stopped being recorded.
const RESERVED = new Set([
  "ad_activeview", "ad_click", "ad_exposure", "ad_impression", "ad_query",
  "ad_reward", "adunit_exposure", "app_background", "app_clear_data",
  "app_exception", "app_remove", "app_store_refund", "app_update",
  "app_store_subscription_cancel", "app_store_subscription_convert",
  "app_store_subscription_renew", "app_upgrade", "dynamic_link_app_open",
  "dynamic_link_app_update", "dynamic_link_first_open", "error", "first_open",
  "first_visit", "in_app_purchase", "notification_dismiss", "os_update",
  "notification_foreground", "notification_open", "notification_receive",
  "session_start", "screen_view", "user_engagement",
]);

const problems = [];
const snake = /^[a-z][a-z0-9_]*$/;
for (const [name, def] of Object.entries(events)) {
  if (!snake.test(name)) problems.push(`event "${name}" is not lower_snake_case`);
  if (name.length > 40) problems.push(`event "${name}" is over the 40 character limit`);
  if (RESERVED.has(name)) problems.push(`event "${name}" is reserved by Google Analytics`);
  if (/^(firebase|google|ga)_/.test(name)) problems.push(`event "${name}" uses a reserved prefix`);
  const params = Object.keys(def.params || {});
  if (params.length > 25) problems.push(`event "${name}" declares more than 25 parameters`);
  for (const p of params) {
    if (!snake.test(p)) problems.push(`parameter "${p}" of "${name}" is not lower_snake_case`);
    if (p.length > 40) problems.push(`parameter "${p}" of "${name}" is over the 40 character limit`);
  }
  // An event nobody can justify is an event nobody will ever read.
  if (!def.why) problems.push(`event "${name}" has no "why"`);
}
if (Object.keys(events).length > 500) problems.push("more than 500 distinct event names");

if (problems.length) {
  console.error(`analytics spec invalid: ${problems.length} problem(s)\n`);
  for (const p of problems) console.error(`  - ${p}`);
  process.exit(1);
}

const pascal = (s) => s.split("_").map((w) => w[0].toUpperCase() + w.slice(1)).join("");
const camel = (s) => { const p = pascal(s); return p[0].toLowerCase() + p.slice(1); };

const allParams = [
  ...new Set(Object.values(events).flatMap((e) => Object.keys(e.params || {}))),
].sort();

const header = (lang) => `// Generated by scripts/gen-analytics.mjs from design/analytics.json.
// Do not edit: the two platforms share one vocabulary and this file is how.
// ${lang}
`;

/** The "why" and the parameter meanings, as the target language writes docs. */
const doc = (def, indent, lang) => {
  const lines = [def.why];
  const params = Object.entries(def.params || {});
  if (params.length) {
    lines.push("");
    for (const [p, meaning] of params) lines.push(`- ${p}: ${meaning}`);
  }
  if (lang === "swift") return lines.map((l) => `${indent}/// ${l}`.trimEnd()).join("\n");
  return [
    `${indent}/**`,
    ...lines.map((l) => `${indent} * ${l}`.trimEnd()),
    `${indent} */`,
  ].join("\n");
};

const swift = `${header("Swift")}
/// Every event the apps may log.
enum Event: String {
${Object.entries(events).map(([name, def]) =>
  `${doc(def, "    ", "swift")}\n    case ${camel(name)} = "${name}"`).join("\n\n")}
}

/// Every parameter name, so no call site spells one.
enum Param: String {
${allParams.map((p) => `    case ${camel(p)} = "${p}"`).join("\n")}
}
`;

const kotlin = `${header("Kotlin")}
package com.mercato.analytics

/** Every event the apps may log. */
enum class Event(val key: String) {
${Object.entries(events).map(([name, def]) =>
  `${doc(def, "    ", "kotlin")}\n    ${name.toUpperCase()}("${name}"),`).join("\n\n")}
}

/** Every parameter name, so no call site spells one. */
enum class Param(val key: String) {
${allParams.map((p) => `    ${p.toUpperCase()}("${p}"),`).join("\n")}
}
`;

fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(path.join(OUT, "AnalyticsEvents.swift"), swift);
fs.writeFileSync(path.join(OUT, "AnalyticsEvents.kt"), kotlin);

console.log(
  `generated build/analytics/AnalyticsEvents.{swift,kt}: ` +
    `${Object.keys(events).length} events, ${allParams.length} distinct parameters`
);
